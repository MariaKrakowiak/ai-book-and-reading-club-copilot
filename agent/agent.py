import os
import json
from databricks.sdk import WorkspaceClient
from databricks.sdk.service.serving import ChatMessage, ChatMessageRole

from agent.prompts import SYSTEM_PROMPT
from agent.tools import (
    search_books,
    get_club_ratings,
    add_book_to_club,
    rate_book,
    update_reading_progress,
    save_note
)


TOOLS = [
    search_books,
    get_club_ratings,
    add_book_to_club,
    rate_book,
    update_reading_progress,
    save_note
]


class ReadingClubAgent:

    def __init__(self):
        self.model_endpoint = os.environ.get(
            "MODEL_SERVING_ENDPOINT"
        )

        if not self.model_endpoint:
            raise RuntimeError(
                "MODEL_SERVING_ENDPOINT is not configured."
            )
        
        # Initialize Databricks SDK client
        # In Databricks Apps, authentication happens automatically
        self.client = WorkspaceClient()

    def answer(self, user_message, context=None):
        """
        Process a natural-language reading-club request.
        Calls the configured Model Serving endpoint to generate AI responses.
        """
        
        try:
            # Prepare messages for the chat completion
            messages = [
                ChatMessage(
                    role=ChatMessageRole.SYSTEM,
                    content=SYSTEM_PROMPT
                ),
                ChatMessage(
                    role=ChatMessageRole.USER,
                    content=user_message
                )
            ]
            
            # Add context if provided
            if context:
                context_str = json.dumps(context) if isinstance(context, dict) else str(context)
                messages.insert(1, ChatMessage(
                    role=ChatMessageRole.SYSTEM,
                    content=f"Context: {context_str}"
                ))
            
            # Call the Model Serving endpoint
            response = self.client.serving_endpoints.query(
                name=self.model_endpoint,
                messages=messages,
                max_tokens=1000,
                temperature=0.7
            )
            
            # Extract the response message
            if response.choices and len(response.choices) > 0:
                assistant_message = response.choices[0].message.content
                return {
                    "message": assistant_message,
                    "model": self.model_endpoint
                }
            else:
                return {
                    "message": "No response generated by the model.",
                    "model": self.model_endpoint
                }
                
        except Exception as e:
            # Return error details for debugging
            return {
                "message": f"Error calling model endpoint: {str(e)}",
                "error": str(e),
                "model": self.model_endpoint
            }
